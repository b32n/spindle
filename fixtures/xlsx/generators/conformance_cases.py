CASES = []
_counts = {}


def case(function, formula, cells=None, **options):
    _counts[function] = _counts.get(function, 0) + 1
    CASES.append({"id": f"{function.lower().replace('.', '_')}-{_counts[function]:02d}", "function": function, "formula": formula, "cells": cells or {}, **options})


