"""Case table for the formula conformance oracle (plan S11): batch-A functions, one row per formula.

Every case is (function, formula in editor syntax, input cells, options). The formula sits in AA1 of a sheet of its own
(the same place the Jest test puts it); `cells` maps A1 refs to a number, string, bool, None (blank), an error literal
(`'#DIV/0!'`, `'#N/A'`, `'#VALUE!'`, `'#NUM!'`) or a formula string starting with `=`. Options:

    spill=(rows, cols)  the formula returns an array: the oracle records that block (a legacy array formula for LibreOffice)
    array=True          evaluate in array context (CSE) so LibreOffice computes element-wise like Excel 365 does
    excel=<value>       LibreOffice differs from Excel here: the documented Excel value is used, the row is tagged
                        `excel: true, unverified: true` and LibreOffice's value is kept in `libreoffice`
    note=<text>         why (required with `excel`)
"""

