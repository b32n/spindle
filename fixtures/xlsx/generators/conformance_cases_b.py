"""Case table for the formula conformance oracle (plan S12): batch-B functions (text, date, finance, array).

Same format as conformance_cases.py (read its docstring), and the rows land in the "batch-b" group.

A row whose value LibreOffice gets wrong, or computes differently from Excel, carries the value Excel's documentation gives and is tagged
`excel: true, unverified: true` until a real Excel file confirms it (plan D8); `unverified=` flags a row that keeps LibreOffice's value but
whose agreement with Excel is not known. TEXTBEFORE, TEXTAFTER and TEXTSPLIT are deferred until Excel-computed files exist (LibreOffice
25.2 has no such function, so there is no oracle: plan S12, D8).
"""
from conformance_cases import NOTE_502, NUM, case  # noqa: F401


def b(function, formula, cells=None, **options):
    case(function, formula, cells, group="batch-b", **options)


def no_lo(function, value=None):
    """The `excel`/`note` options of a row for a function LibreOffice 25.2 does not have."""
    return {"excel": value, "note": f"LibreOffice 25.2 has no {function}; the value is Excel's documented behaviour, unverified until a real Excel file confirms it (D8)"}


