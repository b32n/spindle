"""Regenerate every fixture whose generator lives in this directory.

    python3 fixtures/docx/generators/build_all.py            # all
    python3 fixtures/docx/generators/build_all.py revisions-authors

Fixtures produced by an external tool (LibreOffice re-saves) are listed in manifest.json with the
exact command; they are generated by their own script and committed as binaries.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import build_revisions  # noqa: E402
import build_styles_lists  # noqa: E402

BUILDERS = {
    "styles-lists": build_styles_lists.build,
    "revisions-authors": build_revisions.build,
}


def main(argv):
    wanted = argv or sorted(BUILDERS)
    for name in wanted:
        if name not in BUILDERS:
            raise SystemExit(f"unknown fixture {name!r}; known: {', '.join(sorted(BUILDERS))}")
        path = os.path.join(OUT, f"{name}.docx")
        BUILDERS[name](path)
        print(f"wrote {path} ({os.path.getsize(path)} bytes)")


if __name__ == "__main__":
    main(sys.argv[1:])
