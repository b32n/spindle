import { readFileSync } from 'node:fs';
import path from 'node:path';
import { CONSTRUCTS, readParts, unverifiedClaims } from './constructs';
import { loadManifest } from './manifest';

export const MATRIX_START = '<!-- coverage-matrix:start (generated by `npm run docs:docx-fidelity -- --matrix`; do not edit) -->';
export const MATRIX_END = '<!-- coverage-matrix:end -->';

/** Markdown feature x fixture matrix built from the manifest's claims; a cell is "yes" only for claimed constructs. */
export function buildMatrix(fixtures: Array<{ id: string; constructs: string[] }>): string {
  const ids = fixtures.map((f) => f.id);
  const header = `| Construct | ${ids.map((i) => `\`${i}\``).join(' | ')} |`;
  const sep = `|---|${ids.map(() => ':-:').join('|')}|`;
  const rows = CONSTRUCTS.map((c) => `| ${c.label} (\`${c.id}\`) | ${fixtures.map((f) => (f.constructs.includes(c.id) ? 'yes' : '')).join(' | ')} |`);
  return [header, sep, ...rows].join('\n');
}

/** Constructs in the vocabulary that no fixture claims. */
export function uncoveredConstructs(fixtures: Array<{ constructs: string[] }>): string[] {
  return CONSTRUCTS.map((c) => c.id).filter((id) => !fixtures.some((f) => f.constructs.includes(id)));
}

/** Replace the generated block in a README with a fresh matrix. */
export function injectMatrix(readme: string, matrix: string): string {
  const a = readme.indexOf(MATRIX_START);
  const b = readme.indexOf(MATRIX_END);
  if (a < 0 || b < a) throw new Error('README is missing the coverage-matrix markers');
  return `${readme.slice(0, a)}${MATRIX_START}\n\n${matrix}\n\n${readme.slice(b)}`;
}

/** Every construct a fixture claims must actually be present in its OOXML; returns the false claims. */
export async function verifyClaims(fixturesDir: string): Promise<string[]> {
  const problems: string[] = [];
  for (const f of loadManifest(fixturesDir).fixtures) {
    let parts;
    try {
      parts = await readParts(new Uint8Array(readFileSync(path.join(fixturesDir, f.filename))));
    } catch {
      // unreadable zip: only the malformed-container constructs can be claimed (they are checked by hand in the manifest)
      if (f.constructs.some((c) => !c.startsWith('edge.'))) problems.push(`${f.id}: file is not a readable zip but claims non-edge constructs`);
      continue;
    }
    for (const c of unverifiedClaims(f.constructs, parts)) problems.push(`${f.id}: claims "${c}" but the file does not contain it`);
  }
  return problems;
}
