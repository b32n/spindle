// Generates docs/testing/scenarios.md from the E2E specs so the map cannot drift.
//   node scripts/testing/scenarios.mjs          # (re)write the file
//   node scripts/testing/scenarios.mjs --check  # exit 1 if the file is stale
//
// Every `test('ID title', ...)` / `test.fixme('ID title', ...)` whose title starts
// with an ID like `S-SEL-01` becomes a row. Status is `covered`, or `fixme + bug`
// (the `// Bug:` comment block directly above the test is used as the note).
// Scenarios that are intentionally absent live in GAPS below.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const specRoot = path.join(root, 'e2e');
const outFile = path.join(root, 'docs', 'testing', 'scenarios.md');

const EDITORS = {
  sheets: 'Sheets',
  docs: 'Docs',
  slides: 'Slides',
};

/** Scenarios with no E2E test: status is `n/a` (nothing to test) or `not covered` (todo). */
const GAPS = [
  ['sheets', 'S-GAP-01', 'Import / export (CSV, XLSX) UI', 'n/a', 'No import/export UI exists in the sheets toolbar or demo yet; file round-trips stay in sheets-core unit tests.'],
  ['sheets', 'S-GAP-02', 'Ctrl/Cmd-click multi-range selection', 'n/a', 'The grid supports a single selection range only.'],
  ['sheets', 'S-GAP-03', 'HTML clipboard paste', 'n/a', 'Sheets reads/writes plain text (TSV) only; there is no HTML clipboard path.'],
  ['sheets', 'S-GAP-04', 'Touch gestures', 'not covered', 'Touch / mobile is untested (see the maintenance plan).'],
  ['sheets', 'S-GAP-05', 'Formula engine semantics (146 functions)', 'n/a', 'Deliberately kept in fast unit tests (sheets-core).'],
  ['docs', 'D-GAP-01', 'Import / export (DOCX) UI', 'n/a', 'No import/export UI exists in docs-react / the demo yet; round-trips stay in docs-core unit tests.'],
  ['docs', 'D-GAP-02', 'Triple-click paragraph selection and mouse drag selection', 'not covered', 'Needs a stable way to read the ProseMirror selection; double-click is covered (D-SEL-02).'],
  ['docs', 'D-GAP-03', 'Ruler margin handles, table column resize, image resize handles', 'not covered', 'Pointer gestures on the canvas-like page layer; to add.'],
  ['docs', 'D-GAP-04', 'Headers/footers in additional sections, odd/even pages', 'n/a', 'Not supported by the product yet.'],
  ['docs', 'D-GAP-05', 'Suggestion / review mode', 'n/a', 'Not implemented (missing everywhere).'],
  ['slides', 'SL-GAP-01', 'Import / export (PPTX / PDF) UI', 'n/a', 'No import/export UI exists in slides-react / the demo.'],
  ['slides', 'SL-GAP-02', 'Presenter view in a separate window', 'not covered', 'Opens a popup window; only the S-key notes panel is covered (SL-PRS-06).'],
  ['slides', 'SL-GAP-03', 'Connector snapping to anchors, table cell selection gestures', 'not covered', 'Complex pointer gestures; to add.'],
  ['slides', 'SL-GAP-04', 'Slide drag-reorder in the filmstrip', 'not covered', 'To add.'],
];

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    if (n.startsWith('.')) return [];
    const p = path.join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.spec.ts') ? [p] : [];
  });
}

const rows = [];
for (const file of walk(specRoot)) {
  const rel = path.relative(specRoot, file).split(path.sep);
  const editor = rel.length > 1 ? rel[0] : null;
  if (!editor || !EDITORS[editor]) continue;
  const lines = readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const m = line.match(/^\s*test(\.fixme)?\(\s*(['"`])([A-Z]+-[A-Z]+-\d+[a-z]?) (.*?)\2/);
    if (!m) return;
    const fixme = !!m[1];
    let note = '';
    if (fixme) {
      const buf = [];
      for (let j = i - 1; j >= 0 && /^\s*\/\//.test(lines[j]); j--) buf.unshift(lines[j].replace(/^\s*\/\/\s?/, ''));
      note = buf.join(' ').replace(/^Bug:\s*/, '').replace(/\|/g, '\\|');
    }
    const smoke = /@smoke/.test(m[4]);
    rows.push({ editor, id: m[3], title: m[4].replace(/\s*@smoke/, '').replace(/\|/g, '\\|'), fixme, note, smoke, file: path.relative(root, file) });
  });
}

const out = [];
out.push('# E2E scenario map', '');
out.push('<!-- GENERATED by scripts/testing/scenarios.mjs - do not edit by hand. Run `npm run docs:scenarios`. -->', '');
out.push('Every row is a Playwright scenario (or a recorded gap). IDs are stable: reference them in test titles, commits and bug reports.');
out.push('Status: **covered** (test exists and passes), **fixme + bug** (test written, `test.fixme()` because of a product bug described in the note), **not covered** (to do), **n/a** (the product has nothing to test yet).', '');
out.push('`@smoke` rows are the subset run by `npm run test:e2e:smoke`.', '');
const total = { covered: 0, fixme: 0, notcovered: 0, na: 0 };
for (const [key, name] of Object.entries(EDITORS)) {
  out.push(`## ${name}`, '', '| ID | Scenario | Status | Smoke | Notes | Spec |', '|---|---|---|---|---|---|');
  const mine = rows.filter((r) => r.editor === key);
  for (const r of mine) {
    r.fixme ? total.fixme++ : total.covered++;
    out.push(`| ${r.id} | ${r.title} | ${r.fixme ? 'fixme + bug' : 'covered'} | ${r.smoke ? 'yes' : ''} | ${r.note} | \`${r.file}\` |`);
  }
  for (const [e, id, title, status, note] of GAPS.filter((g) => g[0] === key)) {
    status === 'n/a' ? total.na++ : total.notcovered++;
    out.push(`| ${id} | ${title} | ${status} | | ${note} | |`);
  }
  out.push('');
}
out.push('## Summary', '', `- covered: ${total.covered}`, `- fixme + bug: ${total.fixme}`, `- not covered: ${total.notcovered}`, `- n/a: ${total.na}`, '');
const text = out.join('\n');

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(outFile, 'utf8'); } catch { /* missing */ }
  if (cur !== text) {
    console.error('docs/testing/scenarios.md is stale. Run: npm run docs:scenarios');
    process.exit(1);
  }
} else {
  writeFileSync(outFile, text);
  console.log(`wrote ${path.relative(root, outFile)} (${rows.length} scenarios)`);
}
