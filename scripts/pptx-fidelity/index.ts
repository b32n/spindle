import path from 'node:path';
import { verifyClaims } from '../fidelity-core/claims';
import { injectMatrix, buildMatrix, uncoveredConstructs } from '../fidelity-core/matrix';
import { loadManifest } from '../fidelity-core/manifest';
import type { Manifest, ManifestOptions } from '../fidelity-core/types';
import { CONSTRUCTS } from './constructs';

/** The PPTX binding of the generic modules: the registry, the file extensions and the README markers. */
export const PPTX_FIXTURES_DIR = path.resolve(__dirname, '../../fixtures/pptx');
export const PPTX_MANIFEST_OPTIONS: ManifestOptions = {
  extensions: ['.pptx', '.pptm', '.ppt'],
  constructIds: CONSTRUCTS.map((c) => c.id),
  label: 'PPTX fixture',
};
export const MATRIX_START =
  '<!-- coverage-matrix:start (generated by PPTX_FIDELITY_UPDATE=1 npm test -w @b32nio/spindle-slides-core -- fidelity; do not edit) -->';
export const MATRIX_END = '<!-- coverage-matrix:end -->';

export const loadPptxManifest = (dir = PPTX_FIXTURES_DIR): Manifest =>
  loadManifest(dir, PPTX_MANIFEST_OPTIONS);
export const verifyPptxClaims = (dir = PPTX_FIXTURES_DIR) =>
  verifyClaims(dir, loadPptxManifest(dir), CONSTRUCTS);
export const pptxMatrix = (manifest: Manifest) => buildMatrix(CONSTRUCTS, manifest.fixtures);
export const uncoveredPptxConstructs = (manifest: Manifest) =>
  uncoveredConstructs(CONSTRUCTS, manifest.fixtures);
export const injectPptxMatrix = (readme: string, matrix: string) =>
  injectMatrix(readme, matrix, MATRIX_START, MATRIX_END);
