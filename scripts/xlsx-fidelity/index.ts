import path from 'node:path';
import { verifyClaims } from '../fidelity-core/claims';
import { injectMatrix, buildMatrix, uncoveredConstructs } from '../fidelity-core/matrix';
import { loadManifest } from '../fidelity-core/manifest';
import type { Manifest, ManifestOptions } from '../fidelity-core/types';
import { CONSTRUCTS } from './constructs';

/** The XLSX binding of the generic modules: the registry, the file extensions and the README markers. */
export const XLSX_FIXTURES_DIR = path.resolve(__dirname, '../../fixtures/xlsx');
export const XLSX_MANIFEST_OPTIONS: ManifestOptions = {
  extensions: ['.xlsx', '.xlsm', '.xls'],
  constructIds: CONSTRUCTS.map((c) => c.id),
  label: 'XLSX fixture',
};
export const MATRIX_START =
  '<!-- coverage-matrix:start (generated by XLSX_FIDELITY_UPDATE=1 npm test -w @b32nio/spindle-sheets-core -- fidelity; do not edit) -->';
export const MATRIX_END = '<!-- coverage-matrix:end -->';

export const loadXlsxManifest = (dir = XLSX_FIXTURES_DIR): Manifest =>
  loadManifest(dir, XLSX_MANIFEST_OPTIONS);
export const verifyXlsxClaims = (dir = XLSX_FIXTURES_DIR) =>
  verifyClaims(dir, loadXlsxManifest(dir), CONSTRUCTS);
export const xlsxMatrix = (manifest: Manifest) => buildMatrix(CONSTRUCTS, manifest.fixtures);
export const uncoveredXlsxConstructs = (manifest: Manifest) =>
  uncoveredConstructs(CONSTRUCTS, manifest.fixtures);
export const injectXlsxMatrix = (readme: string, matrix: string) =>
  injectMatrix(readme, matrix, MATRIX_START, MATRIX_END);
